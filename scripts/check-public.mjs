import fs from 'node:fs';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('dist/index.html');
const bundle=html.match(/src="\/assets\/([^" ]+\.js)"/)[1];
assert.equal(spawnSync(process.execPath,['--check','dist/assets/'+bundle]).status,0);
const article=JSON.parse(read('docs/sage-article.json'));
const media=lang=>article[lang].cases.flatMap(c=>c.medias||[c]);
assert.equal(article.zh.cases.length,4);assert.equal(media('zh').length,10);
assert.deepEqual(article.zh.cases.map(c=>c.medias?.length||1),[1,3,4,2]);
assert.equal(article.zh.cases[2].title,'科研分析');
assert.ok(article.zh.cases[2].medias[1].src.endsWith('/eeg-v2.mp4'));
assert.ok(article.zh.cases[3].medias.every(m=>m.type==='iframe'));
assert.deepEqual(media('zh').map(m=>m.src),media('en').map(m=>m.src));
for(const m of media('zh'))for(const k of ['src','poster'])if(m[k])assert.ok(fs.existsSync('dist'+m[k]),m[k]);
for(const [,ref] of html.matchAll(/(?:src|href)="(\/[^"?]+)/g))assert.ok(fs.existsSync('dist'+ref),ref);
const results=JSON.parse(read('docs/sage-evaluation.json'));
const tsv=read('docs/sage-benchmarks.tsv').trim().split('\n').map(l=>l.split('\t'));
assert.deepEqual(results.columns,tsv[0]);assert.deepEqual(results.rows,tsv.slice(1));
assert.equal(results.rows.length,34);assert.ok(results.rows.every(r=>r.length===10));
assert.equal(results.notes.zh.length,35);assert.equal(results.notes.en.length,35);
assert.deepEqual(results.externalColumns,[7,8,9]);
assert.equal(results.groups.length,8);
const security=results.groups.findIndex(g=>g.en==='Cybersecurity');
assert.deepEqual(results.rows.slice(results.groups[security].start,results.groups[security+1].start).map(r=>r[0]),['CyberGym']);
assert.ok(!JSON.stringify(results).includes('ExploitGym'));
results.rows.forEach((row,r)=>{const scored=row.slice(1,7).map(v=>v==='-'?-Infinity:Number(v));const max=Math.max(...scored);assert.deepEqual(results.best[r],scored.flatMap((v,c)=>v===max?[c+1]:[]));});
assert.ok(read('dist/cases/sage/benchmarks.svg').includes('Sage 2.1 Flash'));
assert.ok(!read('dist/cases/sage/benchmarks.svg').includes('Sage S2.1 Flash'));
console.log('PASS: JS syntax, bilingual demos, local assets, and all 306 benchmark values, 35 bilingual notes, source highlights, and CyberGym-only security group.');
